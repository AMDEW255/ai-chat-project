// ПРИМЕР 3 — промис
// -------------------------------------------------
// wait(ms) возвращает промис, который выполняется через ms миллисекунд.
// (не переживай, если внутри непонятно — важно, что wait(...) возвращает промис)

function wait(ms) {
    return new Promise(function (resolve) {
        setTimeout(resolve, ms);
    });
}

console.log('строка 1 — печатается сразу');
console.log('строка 2 — тоже сразу, ещё до того как пройдут 1.5 секунды');

wait(1500)
.then(function() {
    console.log('Операция 1 выполнена')

    return new Promise(function (resolve) {
        setTimeout(resolve, 2000);
    });
}) // => успешный ответ
.then(function() {
    console.log('Операция 2 выполнена')
}) // => успешный ответ
.then(function() {
    console.log('Операция 3 выполнена')
}) // => успешный ответ
.then(function() {
    console.log('Операция 4 выполнена')
}) // => успешный ответ
.catch(function() {
    console.log('Операция не выполнена')
})
.finally(function() {
    console.log('Все операции завершены')
})

